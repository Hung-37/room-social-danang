// Uses fixtures created by verify-management.mjs; isolated test database only.
const { createRequire } = require('node:module');
const req = createRequire(require('node:path').join(__dirname, '../../package.json'));
const { chromium } = req('playwright');
const { default: AxeBuilder } = req('@axe-core/playwright');
const sharp = req('sharp');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const base = process.env.TEST_BASE_URL,
  fixture = process.env.TEST_MANAGEMENT_FIXTURES;
if (!base || !fixture)
  throw new Error('Set TEST_BASE_URL and TEST_MANAGEMENT_FIXTURES (generated by test:management).');
const out = process.env.TEST_SCREENSHOT_DIR || path.join(__dirname, '../../work/management-browser');
fs.mkdirSync(out, { recursive: true });
(async () => {
  const f = JSON.parse(fs.readFileSync(fixture));
  const browser = await chromium.launch({
    executablePath: process.env.CHROMIUM_PATH || undefined,
    headless: true,
    args: ['--no-sandbox']
  });
  const origin = new URL(base);
  const local = origin.protocol === 'http:';
  if (local) assert(['localhost', '127.0.0.1'].includes(origin.hostname));
  async function context(cookie) {
    const ctx = await browser.newContext({ baseURL: base });
    for (const part of cookie.split('; ')) {
      const split = part.indexOf('=');
      await ctx.addCookies([
        {
          name: part.slice(0, split),
          value: part.slice(split + 1),
          url: base,
          httpOnly: true,
          secure: !local,
          sameSite: 'Lax'
        }
      ]);
    }
    return ctx;
  }
  const owner = await context(f.owner),
    buyer = await context(f.buyer),
    second = await context(f.second),
    admin = await context(f.admin);
  let checks = 0;
  for (const ctx of [owner, buyer, second, admin]) {
    ctx.setDefaultTimeout(15000);
    ctx.setDefaultNavigationTimeout(20000);
  }
  async function api(ctx, url, method = 'GET', data, status = 200) {
    const r = await ctx.request.fetch(url, { method, data });
    const p = await r.json();
    assert.equal(r.status(), status, JSON.stringify(p));
    checks++;
    if (local) await ctx.addCookies((await ctx.cookies()).map((c) => ({ ...c, secure: false })));
    return p.data;
  }
  const p = await owner.newPage(),
    b = await buyer.newPage(),
    s = await second.newPage(),
    a = await admin.newPage();
  const errors = [];
  for (const page of [p, b, s, a]) page.on('pageerror', (e) => errors.push(e.message));
  await api(owner, '/api/profile', 'PATCH', { name: 'Chủ trọ Minh' });
  await api(buyer, '/api/profile', 'PATCH', { name: 'An tìm phòng' });
  const stamp = Date.now(),
    title = 'Phòng ban công dễ thương ' + stamp;
  console.log('STEP: create form');
  await p.goto('/dang-phong');
  await p.getByLabel('Tiêu đề', { exact: true }).fill(title);
  await p
    .getByLabel('Mô tả phòng', { exact: true })
    .fill('Phòng thoáng sáng, có ban công, bếp và chỗ để xe. Phí điện nước ghi rõ trong hợp đồng.');
  await p.getByLabel('Địa chỉ', { exact: true }).fill('12 Nguyễn Văn Linh, Hải Châu, Đà Nẵng');
  await p.getByLabel('Giá thuê / tháng (đồng)', { exact: true }).fill('2800000');
  await p.getByLabel('Diện tích (m²)', { exact: true }).fill('26.5');
  const image = await sharp({
    create: { width: 800, height: 500, channels: 3, background: '#bfdbc5' }
  })
    .png()
    .toBuffer();
  const image2 = await sharp({
    create: { width: 800, height: 500, channels: 3, background: '#d8cdb8' }
  })
    .png()
    .toBuffer();
  await p.getByLabel('Chọn ảnh phòng', { exact: true }).setInputFiles([
    { name: 'phong.png', mimeType: 'image/png', buffer: image },
    { name: 'ban-cong.png', mimeType: 'image/png', buffer: image2 }
  ]);
  await p.getByRole('img', { name: 'Ảnh phòng 2', exact: true }).waitFor();
  checks++;
  await p.getByRole('button', { name: 'Gửi tin chờ duyệt', exact: true }).click();
  await p.waitForURL('**/quan-ly-phong?da-gui=1');
  await p.getByRole('status').filter({ hasText: 'Đã lưu tin.' }).waitFor();
  checks++;
  console.log('STEP: submitted');
  const listing = (await api(owner, '/api/landlord')).listings.find((l) => l.title === title);
  assert(listing);
  const id = listing.externalId;
  await a.goto('/admin?tab=listings');
  await a.getByRole('button', { name: /Quản lý bài/ }).click();
  const review = a.locator('.source-row').filter({ hasText: title });
  await review.getByText('Xem nội dung và ảnh', { exact: true }).click();
  await review.getByRole('img', { name: 'Ảnh phòng 2', exact: true }).waitFor();
  checks++;
  // Also verify every uploaded image is present in the private preview payload.
  const preview = await api(admin, '/api/admin/listings/' + id + '/preview');
  assert.equal(preview.imageUrls.length, 2);
  checks++;
  await api(admin, '/api/listings/' + id + '/status', 'POST', { status: 'verified' });
  console.log('STEP: approved');
  await b.goto('/bang-tin');
  await b.getByRole('searchbox', { name: 'Tìm kiếm', exact: true }).fill(title);
  const card = b.locator('.room-card').filter({ hasText: title });
  await card.getByRole('button', { name: 'Lưu: ' + title, exact: true }).click();
  await card.getByRole('button', { name: 'Bỏ lưu: ' + title, exact: true }).waitFor();
  checks++;
  console.log('STEP: saved');
  await s.goto('/profile');
  await s.getByRole('heading', { name: title, exact: true }).waitFor();
  checks++;
  await s.getByRole('button', { name: 'Chỉnh sửa hồ sơ', exact: true }).click();
  await s.getByLabel('Tên hiển thị', { exact: true }).fill('An Nguyễn');
  await s.getByRole('button', { name: 'Lưu hồ sơ', exact: true }).click();
  await s.getByText('Đã lưu hồ sơ vào tài khoản.', { exact: true }).waitFor();
  await b.goto('/profile');
  await b.getByRole('heading', { name: 'An Nguyễn', exact: true }).waitFor();
  checks++;
  await b.goto('/bai/' + id);
  await b.getByRole('button', { name: 'Xem ảnh phòng 2', exact: true }).click();
  assert.equal(await b.locator('.detail-cover img').getAttribute('src'), preview.imageUrls[1]);
  checks++;
  await p.goto('/quan-ly-phong/' + id);
  await p.getByLabel('Giá thuê / tháng (đồng)', { exact: true }).fill('2900000');
  await p.getByRole('button', { name: 'Lưu và gửi duyệt lại', exact: true }).click();
  await p.waitForURL('**/quan-ly-phong?da-gui=1');
  await api(buyer, '/api/community/posts/' + id, 'GET', undefined, 404);
  checks++;
  await api(admin, '/api/listings/' + id + '/status', 'POST', { status: 'verified' });
  await p.reload();
  const managed = p.locator('.management-room').filter({ hasText: title });
  await managed.getByRole('button', { name: 'Đã hết phòng', exact: true }).click();
  await p
    .getByRole('region', { name: 'Xác nhận đổi trạng thái' })
    .getByRole('button', { name: 'Xác nhận', exact: true })
    .click();
  await managed.locator('.listing-status').getByText('Đã hết phòng', { exact: true }).waitFor();
  await api(buyer, '/api/community/posts/' + id, 'GET', undefined, 404);
  checks++;
  await managed.getByRole('button', { name: 'Gửi duyệt lại', exact: true }).click();
  await p
    .getByRole('region', { name: 'Xác nhận đổi trạng thái' })
    .getByRole('button', { name: 'Xác nhận', exact: true })
    .click();
  await managed.locator('.listing-status').getByText('Chờ duyệt', { exact: true }).waitFor();
  checks++;
  await managed.getByRole('button', { name: 'Ẩn tin', exact: true }).click();
  await p
    .getByRole('region', { name: 'Xác nhận đổi trạng thái' })
    .getByRole('button', { name: 'Xác nhận', exact: true })
    .click();
  await managed.locator('.listing-status').getByText('Đã ẩn', { exact: true }).waitFor();
  checks++;
  await b.goto('/profile');
  await b.getByRole('heading', { name: 'Tin không còn công khai', exact: true }).waitFor();
  checks++;
  const scans = [];
  for (const width of [1440, 390]) {
    for (const [page, url, label] of [
      [p, '/quan-ly-phong', 'management'],
      [p, '/dang-phong', 'create'],
      [p, '/quan-ly-phong/' + id, 'edit'],
      [b, '/profile', 'profile']
    ]) {
      await page.setViewportSize({ width, height: 900 });
      await page.goto(url);
      await page.waitForTimeout(700);
      assert(
        await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1),
        label + ' overflow ' + width
      );
      checks++;
      const result = await new AxeBuilder({ page })
        .withTags(['wcag2a', 'wcag2aa', 'wcag21a', 'wcag21aa'])
        .analyze();
      scans.push({
        width,
        label,
        violations: result.violations.map((v) => ({
          id: v.id,
          impact: v.impact,
          nodes: v.nodes.map((n) => n.target)
        }))
      });
      await page.screenshot({ path: path.join(out, label + '-' + width + '.png'), fullPage: true });
    }
  }
  for (const page of [p, b]) {
    await page.setViewportSize({ width: 320, height: 800 });
    await page.reload();
    await page.waitForTimeout(500);
    assert(
      await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1),
      '320 overflow'
    );
    checks++;
  }
  await b.getByRole('button', { name: 'Bỏ lưu: Tin không còn công khai', exact: true }).click();
  await b.getByText('Bạn chưa lưu bài nào.', { exact: false }).waitFor();
  await s.reload();
  await s.getByText('Bạn chưa lưu bài nào.', { exact: false }).waitFor();
  checks++;
  assert.deepEqual(errors, []);
  fs.writeFileSync(path.join(out, 'accessibility.json'), JSON.stringify(scans, null, 2));
  assert(
    scans.every((s) => s.violations.length === 0),
    JSON.stringify(scans)
  );
  console.log(JSON.stringify({ checks, errors, scans }, null, 2));
  await browser.close();
})().catch((e) => {
  console.error(e);
  process.exit(1);
});
